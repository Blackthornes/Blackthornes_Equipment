"""Writes Data/ForeverQuests.lua: quests and quest rewards met on WoW:
Forever that the Classic data in Data/Sources.lua lacks.

Run from the repository root:

    python tools/forever_quests.py [saved file ...]

A saved file is the addon's account save, Blackthornes_Equipment.lua from
the game's WTF/Account/<account>/SavedVariables folder. Only its
`learnedQuests` table is read (Logic/QuestLearn.lua: quest ID -> title,
levels, who gave it and where, and the gear it rewards), so nothing about
the player or their characters is copied.

The quests already in Data/ForeverQuests.lua are kept, and a newer reading
of the same quest adds to them. A quest the Classic data already has, with
every reward linked, is left out, since there is nothing to add.

Options:
    --stdout   print the file instead of writing it
"""

import os
import sys

from lupa import lua51

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from forever_npcs import READ_SAVE, lua_string, num, run_file  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "Data", "ForeverQuests.lua")


def classic(lua):
    """(quest IDs, {itemID: (quest IDs, given quest IDs)}) from Data/Sources.lua."""
    lua.execute("ns = {}")
    run_file(lua, os.path.join(ROOT, "Data", "Sources.lua"))
    data = lua.eval("ns.Sources")
    quests = {int(q) for q in data.QUESTS}
    items = {}
    for item_id in data.ITEMS:
        row = data.ITEMS[item_id]
        q = {int(v) for v in (row.q or {}).values()}
        g = {int(v) for v in (row.g or {}).values()}
        items[int(item_id)] = (q, g)
    return quests, items


def clean(raw):
    """One quest record, checked field by field; None when it is unusable."""
    try:
        if not raw["title"]:
            return None
        rec = {"title": str(raw["title"])}
        for key in ("level", "min"):
            if raw[key] is not None:
                rec[key] = int(raw[key])
        if raw["giver"] is not None:
            rec["giver"] = str(raw["giver"])
        if raw["zone"] is not None:
            rec["zone"] = str(raw["zone"])
        for key in ("x", "y"):
            if raw[key] is not None:
                rec[key] = float(raw[key])
        rewards = []
        for i in sorted((raw["rewards"] or {}).keys()):
            r = raw["rewards"][i]
            rewards.append((int(r[1]), int(r[2] or 0), int(r[3] or 0), bool(r[4])))
        rec["rewards"] = rewards
        return rec
    except (TypeError, ValueError, KeyError):
        return None


def table_to_records(lua_table):
    found = {}
    for quest_id in lua_table or {}:
        rec = clean(lua_table[quest_id])
        if rec:
            found[int(quest_id)] = rec
        else:
            print(f"skipped a row that could not be read: {quest_id}", file=sys.stderr)
    return found


def from_save(lua, path):
    with open(path, encoding="utf-8") as f:
        db, why = lua.eval(READ_SAVE)(f.read())
    if why:
        print(f"could not read {path}: {why}", file=sys.stderr)
    return table_to_records(db and db.learnedQuests)


def shipped(lua):
    if not os.path.exists(OUTPUT):
        return {}
    lua.execute("ns = {}")
    run_file(lua, OUTPUT)
    return table_to_records(lua.eval("ns.ForeverQuests"))


def merge(old, new):
    """Add a newer reading of a quest to an older one."""
    rec = dict(old)
    for key in ("title", "level", "giver", "zone", "x", "y"):
        if key in new and (key not in rec or key == "level"):
            rec[key] = new[key]
    if "min" in new:
        rec["min"] = min(rec.get("min", new["min"]), new["min"])
    rewards = {r[0]: r for r in rec["rewards"]}
    for r in new["rewards"]:
        have = rewards.get(r[0])
        if have:
            rewards[r[0]] = (r[0], have[1] or r[1], have[2] or r[2], have[3] or r[3])
        else:
            rewards[r[0]] = r
    rec["rewards"] = [rewards[k] for k in sorted(rewards)]
    return rec


def new_to_classic(quest_id, rec, quests, items):
    """Does the record say anything Classic's data does not?"""
    if quest_id not in quests:
        return True
    for item_id, _req, _ilvl, given in rec["rewards"]:
        q, g = items.get(item_id, (set(), set()))
        if quest_id not in q or (given and quest_id not in g):
            return True
    return False


def render(records):
    lines = [
        "-- Blackthornes Equipment -- Data/ForeverQuests.lua",
        "-- Quests and quest rewards met on WoW: Forever that the Classic data in",
        "-- Data/Sources.lua lacks.",
        "--",
        "-- Generated by tools/forever_quests.py from quests seen in game",
        "-- (Logic/QuestLearn.lua keeps one whenever a quest is offered or handed",
        "-- in). Do not edit by hand: rerun the tool. Each quest ID lists",
        "-- { title, level, min, giver, zone, x, y, rewards = { { itemID, required",
        "-- level, item level, given }, ... } }, as Logic/QuestLearn.lua keeps them.",
        "",
        "local _, ns = ...",
        "",
        "ns.ForeverQuests = {",
    ]
    for quest_id in sorted(records):
        rec = records[quest_id]
        parts = [f"title = {lua_string(rec['title'])}"]
        for key in ("level", "min"):
            if key in rec:
                parts.append(f"{key} = {rec[key]}")
        for key in ("giver", "zone"):
            if key in rec:
                parts.append(f"{key} = {lua_string(rec[key])}")
        for key in ("x", "y"):
            if key in rec:
                parts.append(f"{key} = {num(rec[key])}")
        rewards = ", ".join(
            "{ %d, %d, %d, %s }" % (i, req, ilvl, "true" if given else "false")
            for i, req, ilvl, given in rec["rewards"]
        )
        parts.append("rewards = { " + rewards + " }" if rewards else "rewards = {}")
        lines.append(f"    [{quest_id}] = {{ " + ", ".join(parts) + " },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv):
    to_stdout = "--stdout" in argv
    saves = [a for a in argv if a != "--stdout"]
    lua = lua51.LuaRuntime(unpack_returned_tuples=True, register_eval=False)
    quests, items = classic(lua)
    records = shipped(lua)
    for path in saves:
        for quest_id, rec in from_save(lua, path).items():
            records[quest_id] = merge(records[quest_id], rec) if quest_id in records else rec
    kept = {q: r for q, r in records.items() if new_to_classic(q, r, quests, items)}
    text = render(kept)
    if to_stdout:
        sys.stdout.write(text)
    else:
        with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"{len(kept)} quests written to Data/ForeverQuests.lua")


if __name__ == "__main__":
    main(sys.argv[1:])
