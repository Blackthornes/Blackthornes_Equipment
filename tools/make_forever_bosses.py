"""Writes Data/ForeverBosses.lua: every boss of each of Forever's own
dungeons and raids, in the order the game lists them, so Dungeon Loot can
show a boss before anyone has seen it drop gear.

Run from the repository root:

    python tools/make_forever_bosses.py <tables folder> [--build 1.60.1.70658] [--stdout]

The tables folder holds the Forever client's game tables as CSV, one file
per table. Only DungeonEncounter is read: each boss's name, the map it is
in, its difficulty and its place in the list. The tables are never copied
into the repository; only the names go in the file.

The dungeons are those in ns.FOREVER_DUNGEON_PLACES (Data/DungeonQuests.lua),
by the map ID the game gives inside. Only the normal difficulty (0) is
kept, test bosses ("Testwerk") are left out, and a name the game shows
differently in play goes through RENAMES, so the name a player sees wins.

Rerun it whenever the client tables are pulled again, and after a Forever
dungeon is added to Data/DungeonQuests.lua.

Options:
    --build    the client build, written in the file's header
    --stdout   print the file instead of writing it
"""

import csv
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "Data", "ForeverBosses.lua")
PLACES = os.path.join(ROOT, "Data", "DungeonQuests.lua")

# The table's name for a boss the game shows by another name in play:
# { "map ID": { "table name": "name in game" } }. Only where the match is
# sure: the one boss left over on both sides once the rest match by name.
RENAMES = {
    "3065": {"Infurnus": "Magmatus"},  # The Hall of Thanes
}

# Bosses the tables hold only for testing.
TEST = re.compile(r"^Test", re.I)

PLACE = re.compile(r'^\s+\["(\d+)"\] = \{ "((?:[^"\\]|\\.)*)"', re.M)


def read_places(path):
    """{ map ID: dungeon name } from ns.FOREVER_DUNGEON_PLACES."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    at = text.find("ns.FOREVER_DUNGEON_PLACES = {")
    if at < 0:
        return {}
    end = text.find("\n}", at)
    return dict(PLACE.findall(text[at:end if end >= 0 else len(text)]))


def number(value):
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return None


def bosses(folder, places):
    """{ map ID: [ name, ... ] } in the game's order, for the places given."""
    found = {}
    with open(os.path.join(folder, "DungeonEncounter.csv"), encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            key = str(number(row.get("MapID")))
            name = (row.get("Name_lang") or "").strip()
            if key not in places or not name or TEST.match(name):
                continue
            if number(row.get("DifficultyID")) not in (0, None):
                continue
            order = number(row.get("OrderIndex"))
            found.setdefault(key, []).append((order if order is not None else 999, name))
    result = {}
    for key, rows in found.items():
        names = []
        for _, name in sorted(rows, key=lambda r: r[0]):
            name = RENAMES.get(key, {}).get(name, name)
            if name not in names:
                names.append(name)
        result[key] = names
    return result


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(found, places, build):
    lines = [
        "-- Blackthornes Equipment -- Data/ForeverBosses.lua",
        "-- Every boss of Forever's own dungeons and raids, in the game's order,",
        "-- by the same key as ns.FOREVER_DUNGEON_PLACES. Dungeon Loot lists a",
        "-- boss here even before anyone has seen it drop gear.",
        "--",
        "-- Generated by tools/make_forever_bosses.py from the Forever client's",
        "-- game tables (build %s). Do not edit by hand: rerun the tool." % build,
        "",
        "local _, ns = ...",
        "",
        "ns.FOREVER_BOSSES = {",
    ]
    for key in sorted(found, key=int):
        names = ", ".join(lua_string(n) for n in found[key])
        lines.append("    [%s] = { %s }, -- %s" % (lua_string(key), names, places.get(key, "")))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv):
    args = [a for a in argv if not a.startswith("--")]
    build = "unknown"
    if "--build" in argv:
        at = argv.index("--build")
        if at + 1 < len(argv):
            build = argv[at + 1]
            args = [a for a in args if a != build]
    if not args:
        print(__doc__)
        return 1
    places = read_places(PLACES)
    text = render(bosses(args[0], places), places, build)
    if "--stdout" in argv:
        sys.stdout.write(text)
    else:
        with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("Wrote " + os.path.relpath(OUTPUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
