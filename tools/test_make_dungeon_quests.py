"""Tests for tools/make_dungeon_quests.py. Run: python tools/test_make_dungeon_quests.py"""

import os
import shutil
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_dungeon_quests as tool  # noqa: E402
import make_sources as ms  # noqa: E402

checks = 0
failures = 0


def expect(label, ok):
    global checks, failures
    checks += 1
    if not ok:
        failures += 1
        print("FAIL: " + label)


folder = tempfile.mkdtemp()
try:
    instance = next(iter(ms.INSTANCES))
    with open(os.path.join(folder, "AreaTable.csv"), "w", encoding="utf-8") as f:
        f.write("ID,ZoneName,ContinentID\n2437,Ragefire,%d\n12,Elwynn,0\n" % instance)
    with open(os.path.join(folder, "QuestV2.csv"), "w", encoding="utf-8") as f:
        f.write("ID,UniqueBitFlag\n5722,1\n5723,2\n")
    maps = tool.area_maps(Path(folder))
    expect("a zone inside an instance maps to it", maps.get(2437) == instance)
    expect("an open world zone does not", 12 not in maps)
    quests = tool.forever_quests(Path(folder))
    expect("the client's quest IDs are read", quests == {5722, 5723})
finally:
    shutil.rmtree(folder)

data = Path(__file__).resolve().parent.parent / "Data" / "DungeonQuests.lua"
text = data.read_text(encoding="utf-8")
expect("the data says it is generated", "Generated by tools/make_dungeon_quests.py" in text)
expect("the data has Forever's own dungeons", "ns.FOREVER_DUNGEON_PLACES" in text)

print("%d checks, %d failed" % (checks, failures))
sys.exit(1 if failures else 0)
