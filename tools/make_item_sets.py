"""Writes Data/ItemSets.lua: the gear sets, which items are in each, and the
stats each set bonus gives once enough pieces are worn.

Run from the repository root:

    python tools/make_item_sets.py <tables folder> [--build 1.60.1.70862] [--stdout]

The tables folder holds the Forever client's game tables as CSV, one file
per table. Read: ItemSet, ItemSetSpell and SpellEffect. The tables are
never copied into the repository.

Only bonuses that give plain stats are kept (strength, spell power, armor,
hit and the like, read the same way tools/make_enchants.py reads an
enchant's equip spell). A bonus that changes a spell or procs gives nothing
here, and a set none of whose bonuses give stats is left out. Rerun it
whenever the client tables are pulled again.

Options:
    --build    the client build, written in the file's header
    --stdout   print the file instead of writing it
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_enchants import (  # noqa: E402
    rows, num, lua_string, lua_list, APPLY_AURA, AURA, AURA_STAT, AURA_RESIST,
    AURA_SPELL_DAMAGE, AURA_SKILL, DEFENSE_SKILL, ARMOR_MASK, STAT_MISC, SCHOOL,
    ALL_SCHOOLS,
)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "Data", "ItemSets.lua")

ITEM_COLUMNS = 17
# Aura types set bonuses use that enchants do not: spell crit chance.
SET_AURA = dict(AURA)
SET_AURA[57] = "spellCrit"


def bonus_stats(effects):
    """{ stat = value } from one bonus spell's effects."""
    stats = {}

    def add(key, value):
        if key and value:
            stats[key] = stats.get(key, 0) + value

    for e in effects:
        if num(e["Effect"]) != APPLY_AURA:
            continue
        aura, misc, value = num(e["EffectAura"]), num(e["EffectMiscValue_0"]), num(e["EffectBasePointsF"])
        if value <= 0:
            continue
        if aura == AURA_STAT:
            for k in (STAT_MISC.values() if misc == -1 else [STAT_MISC.get(misc)]):
                add(k, value)
        elif aura == AURA_RESIST:
            if misc == ARMOR_MASK:
                add("armor", value)
        elif aura == AURA_SPELL_DAMAGE:
            if misc & ALL_SCHOOLS == ALL_SCHOOLS:
                add("spellPower", value)
            else:
                for bit, k in SCHOOL.items():
                    if misc & bit:
                        add(k, value)
        elif aura == AURA_SKILL:
            if misc == DEFENSE_SKILL:
                add("defense", value)
        else:
            add(SET_AURA.get(aura), value)
    return stats


def build(folder):
    effects = {}
    for r in rows(folder, "SpellEffect"):
        effects.setdefault(num(r["SpellID"]), []).append(r)
    bonuses = {}
    for r in rows(folder, "ItemSetSpell"):
        if num(r["ChrSpecID"]) != 0:
            continue
        stats = bonus_stats(effects.get(num(r["SpellID"]), ()))
        if not stats:
            continue
        at = bonuses.setdefault(num(r["ItemSetID"]), {}).setdefault(num(r["Threshold"]), {})
        for k, v in stats.items():
            at[k] = at.get(k, 0) + v
    sets = {}
    for r in rows(folder, "ItemSet"):
        set_id = num(r["ID"])
        if set_id not in bonuses:
            continue
        items = [num(r["ItemID_%d" % i]) for i in range(ITEM_COLUMNS)]
        items = [i for i in items if i > 0]
        if len(items) < 2:
            continue
        sets[set_id] = {
            "items": items,
            "skill": num(r["RequiredSkill"]),
            "rank": num(r["RequiredSkillRank"]),
            "b": bonuses[set_id],
            "name": r["Name_lang"],
        }
    return sets


def write(sets, build_name):
    out = []
    out.append("-- Blackthornes Equipment -- Data/ItemSets.lua")
    out.append("-- Gear sets: the items in each and the stats each set bonus gives.")
    out.append("--")
    out.append("-- Generated by tools/make_item_sets.py from the Forever client's game tables"
               + (" (build %s)" % build_name if build_name else "") + ", never")
    out.append("-- typed by hand.")
    out.append("")
    out.append("local _, ns = ...")
    out.append("")
    out.append("local ItemSetData = {}")
    out.append("ns.ItemSetData = ItemSetData")
    out.append("")
    out.append("-- [set ID] = { items = { item ID }, b = { [pieces worn] = { stat = value } },")
    out.append("--   skill = profession needed, rank = its skill, name }")
    out.append("ItemSetData.SETS = {")
    for set_id in sorted(sets):
        s = sets[set_id]
        parts = ["items = " + lua_list(s["items"])]
        b = []
        for n in sorted(s["b"]):
            st = s["b"][n]
            b.append("[%d] = { %s }" % (n, ", ".join("%s = %d" % (k, v) for k, v in sorted(st.items()))))
        parts.append("b = { " + ", ".join(b) + " }")
        if s["skill"]:
            parts.append("skill = %d" % s["skill"])
            parts.append("rank = %d" % s["rank"])
        parts.append("name = " + lua_string(s["name"]))
        out.append("    [%d] = { %s }," % (set_id, ", ".join(parts)))
    out.append("}")
    out.append("")
    return "\n".join(out)


def main(argv):
    args = list(argv)
    build_name, to_stdout, folder = None, False, None
    while args:
        a = args.pop(0)
        if a == "--build":
            build_name = args.pop(0)
        elif a == "--stdout":
            to_stdout = True
        elif folder is None:
            folder = a
        else:
            raise SystemExit(__doc__)
    if not folder:
        raise SystemExit(__doc__)
    sets = build(folder)
    text = write(sets, build_name)
    if to_stdout:
        sys.stdout.write(text)
    else:
        with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("Wrote %s: %d sets." % (os.path.relpath(OUTPUT, ROOT), len(sets)))


if __name__ == "__main__":
    main(sys.argv[1:])
