"""Writes Data/ForeverGoneQuests.lua: quests in the Classic data in
Data/Sources.lua that the WoW: Forever client does not have.

Run from the repository root:

    python tools/forever_gone_quests.py <tables folder> [--build 1.60.1.70338] [--stdout]

The tables folder holds the Forever client's game tables as CSV, one file
per table. Only QuestV2.csv is read, and only its ID column: every quest
the client knows. The tables are never copied into the repository; only
the IDs of the Classic quests missing from it go in the data file.

The finder leaves those quests out (Finder.DropGoneQuests), so the upgrade
quest never sends anyone after a quest that is not in the game. A quest
learned in game (Logic/QuestLearn.lua) is laid over the data after that,
so it still shows.

Rerun it after tools/make_sources.py, and whenever the client tables are
pulled again. A client table with almost no quests is refused, so a broken
export never empties the data.

Options:
    --build    the client build, written in the file's header
    --stdout   print the file instead of writing it
"""

import csv
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "Data", "ForeverGoneQuests.lua")
SOURCES = os.path.join(ROOT, "Data", "Sources.lua")

# A real client has thousands of quests; fewer means the export went wrong.
FEWEST_CLIENT_QUESTS = 1000

KEY = re.compile(r"^\s+\[(\d+)\] = \{", re.M)


def read_client(folder):
    """The set of quest IDs the client has."""
    path = os.path.join(folder, "QuestV2.csv")
    out = set()
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        if "ID" not in (reader.fieldnames or []):
            raise SystemExit("QuestV2.csv has no column ID")
        for row in reader:
            try:
                out.add(int(row["ID"]))
            except (TypeError, ValueError):
                continue
    return out


def read_quests(path):
    """The quest IDs in Sources.QUESTS."""
    text = open(path, encoding="utf-8").read()
    start = text.find("Sources.QUESTS = {")
    if start < 0:
        raise SystemExit(f"{os.path.basename(path)} has no Sources.QUESTS")
    end = text.find("\n}", start)
    return {int(m.group(1)) for m in KEY.finditer(text[start:end])}


def gone(client, quests):
    """Classic quests the client does not have, lowest first."""
    if len(client) < FEWEST_CLIENT_QUESTS:
        raise SystemExit(f"QuestV2.csv has only {len(client)} quests; is the export whole?")
    return sorted(q for q in quests if q not in client)


def render(ids, build):
    lines = [
        "-- Blackthornes Equipment -- Data/ForeverGoneQuests.lua",
        "-- Quests in the Classic data (Data/Sources.lua) that the WoW: Forever",
        "-- client does not have. The finder leaves them out",
        "-- (Finder.DropGoneQuests); a quest learned in game still shows.",
        "--",
        "-- Generated by tools/forever_gone_quests.py from the Forever client's",
        "-- game tables" + (f" (build {build})" if build else "") + ". Do not edit by hand: rerun the tool.",
        "",
        "local _, ns = ...",
        "",
        "ns.ForeverGoneQuests = {",
    ]
    row = []
    for quest_id in ids:
        row.append(f"[{quest_id}] = true,")
        if len(row) == 8:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv):
    args = [a for a in argv if not a.startswith("--")]
    build = None
    if "--build" in argv:
        at = argv.index("--build")
        if at + 1 >= len(argv):
            raise SystemExit("--build needs a value")
        build = argv[at + 1]
        args = [a for a in args if a != build]
    if len(args) != 1:
        raise SystemExit(__doc__)
    text = render(gone(read_client(args[0]), read_quests(SOURCES)), build)
    if "--stdout" in argv:
        sys.stdout.write(text)
    else:
        with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"Wrote {os.path.relpath(OUTPUT, ROOT)}")


if __name__ == "__main__":
    main(sys.argv[1:])
