"""Writes Data/ForeverNPCs.lua: where vendors and trainers stand on WoW:
Forever, where that differs from the Classic data in Data/Sources.lua and
Data/Crafts.lua.

Run from the repository root:

    python tools/forever_npcs.py [saved file ...] [--spot ID "Zone" X Y [Name]] ...

A saved file is the addon's account save, Blackthornes_Equipment.lua from
the game's WTF/Account/<account>/SavedVariables folder. Only its `npcSpots`
table is read (Logic/NPCSpots.lua: NPC ID -> NPC name, map name, x, y, kept
whenever a merchant or trainer window opens), so nothing about the player
or their characters is copied. `--spot` adds one reading typed in by hand,
for an NPC someone looked up in game.

The spots already in Data/ForeverNPCs.lua are kept, and a newer reading of
the same NPC replaces them. A spot whose map and position match the Classic
data to within half a unit is left out, since there is nothing to fix.

Options:
    --stdout   print the file instead of writing it
"""

import os
import sys

from lupa import lua51

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "Data", "ForeverNPCs.lua")
CLOSE = 0.5   # map units


def run_file(lua, path, ns_expr="ns"):
    chunk = lua.eval("function(path) return assert(loadfile(path)) end")(path)
    chunk("Blackthornes_Equipment", lua.eval(ns_expr))


def classic_spots(lua):
    """npcID -> (zone name, x, y) from the shipped Classic data."""
    spots = {}
    for name, table in (("Sources.lua", "Sources"), ("Crafts.lua", "Crafts")):
        lua.execute("ns = {}")
        run_file(lua, os.path.join(ROOT, "Data", name))
        data = lua.eval("ns." + table)
        if data is None or data.NPCS is None:
            continue
        for npc_id in data.NPCS:
            row = data.NPCS[npc_id]
            spots[int(npc_id)] = (data.ZONES[row[2]], float(row[3]), float(row[4]))
    return spots


def shipped(lua):
    """What Data/ForeverNPCs.lua already holds."""
    if not os.path.exists(OUTPUT):
        return {}
    lua.execute("ns = {}")
    run_file(lua, OUTPUT)
    data = lua.eval("ns.ForeverNPCs")
    found = {}
    for npc_id in data or {}:
        row = data[npc_id]
        found[int(npc_id)] = (row[1] or "", row[2], float(row[3]), float(row[4]))
    return found


def from_save(lua, path):
    """The npcSpots table in one account save, checked row by row."""
    lua.execute("BlackthornesEquipmentDB = nil")
    lua.execute(open(path, encoding="utf-8").read())
    db = lua.eval("BlackthornesEquipmentDB")
    spots = db and db.npcSpots
    found = {}
    for npc_id in spots or {}:
        row = spots[npc_id]
        try:
            spot = (str(row[1] or ""), str(row[2]), float(row[3]), float(row[4]))
            found[int(npc_id)] = spot
        except (TypeError, ValueError):
            print(f"skipped a row that could not be read: {npc_id}", file=sys.stderr)
    return found


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def num(x):
    return ("%.1f" % x).rstrip("0").rstrip(".")


def main(argv):
    to_stdout = "--stdout" in argv
    saves, typed = [], {}
    i = 0
    while i < len(argv):
        arg = argv[i]
        if arg == "--stdout":
            i += 1
        elif arg == "--spot":
            npc_id, zone, x, y = argv[i + 1:i + 5]
            name = ""
            i += 5
            if i < len(argv) and not argv[i].startswith("--") and not os.path.exists(argv[i]):
                name = argv[i]
                i += 1
            typed[int(npc_id)] = (name, zone, float(x), float(y))
        else:
            saves.append(arg)
            i += 1

    lua = lua51.LuaRuntime(unpack_returned_tuples=True)
    classic = classic_spots(lua)
    spots = shipped(lua)
    for path in saves:
        spots.update(from_save(lua, path))
    spots.update(typed)

    kept = {}
    for npc_id, (name, zone, x, y) in spots.items():
        old = classic.get(npc_id)
        if not old:
            continue   # an NPC the finder never shows
        if old[0] == zone and abs(old[1] - x) <= CLOSE and abs(old[2] - y) <= CLOSE:
            continue
        kept[npc_id] = (name, zone, x, y)

    lines = [
        "-- Blackthornes Equipment -- Data/ForeverNPCs.lua",
        "-- Where vendors and trainers stand on WoW: Forever, where that differs",
        "-- from the Classic spots in Data/Sources.lua and Data/Crafts.lua.",
        "--",
        "-- Generated by tools/forever_npcs.py from spots seen in game",
        "-- (Logic/NPCSpots.lua keeps one whenever a merchant or trainer window",
        "-- opens). Do not edit by hand: rerun the tool. Each NPC ID lists",
        "-- { name on Forever (\"\" when not seen), map name, x, y }.",
        "",
        "local _, ns = ...",
        "",
        "ns.ForeverNPCs = {",
    ]
    for npc_id in sorted(kept):
        name, zone, x, y = kept[npc_id]
        lines.append(f"    [{npc_id}] = {{ {lua_string(name)}, {lua_string(zone)}, {num(x)}, {num(y)} }},")
    lines.append("}")
    text = "\n".join(lines) + "\n"

    if to_stdout:
        sys.stdout.write(text)
    else:
        with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"{len(kept)} NPC spots written to Data/ForeverNPCs.lua")


if __name__ == "__main__":
    main(sys.argv[1:])
